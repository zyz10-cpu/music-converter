/**
 * 判断是否为 KGMA / KGM 文件（依据 28 字节魔数）。
 * @param {Uint8Array} buf
 * @returns {boolean}
 */
function isKgm(buf) {
  if (!buf || buf.length < HEADER_LEN) return false;
  for (let i = 0; i < MAGIC_HEADER.length; i++) {
    if (buf[i] !== MAGIC_HEADER[i]) return false;
  }
  return true;
}

/**
 * 解密 KGMA / KGM 文件，返回还原后的音频数据（MP3 / FLAC / ...）。
 * 每 4MB 让出一次事件循环并回报进度，避免大文件时界面假死。
 * @param {Uint8Array} buf 原始文件字节
 * @param {Uint8Array} keyTable 73,155,904 字节公钥表
 * @param {(progress: number) => void} [onProgress] 可选进度回调，0~1
 * @returns {Promise<Uint8Array>} 还原后的音频数据
 */
async function decrypt(buf, keyTable, onProgress) {
  const ownKey = new Uint8Array(17);
  ownKey.set(buf.subarray(0x1c, 0x2c), 0); // 头部偏移 0x1c 的 16 字节 + 1 个零字节

  const src = buf.subarray(HEADER_LEN);
  const audioLen = src.length;
  const out = new Uint8Array(audioLen);
  const mend = PUB_KEY_MEND;

  for (let i = 0; i < audioLen; i++) {
    const med = ownKey[i % 17] ^ src[i];
    const msk = mend[i % 272] ^ keyTable[i >> 4];
    out[i] = (med ^ ((med & 0x0f) << 4)) ^ (msk ^ ((msk & 0x0f) << 4));
    if ((i & 0x3fffff) === 0x3fffff) { // 每 4MB
      if (onProgress) onProgress((i + 1) / audioLen);
      await new Promise((r) => setTimeout(r, 0)); // 让出事件循环，界面不卡
    }
  }
  if (onProgress) onProgress(1);
  return out;
}

/**
 * 嗅探还原后音频的真实格式，返回扩展名。
 * @param {Uint8Array} buf
 * @returns {string} 'mp3' | 'flac' | 'ogg' | 'wav' | 'aac'
 */
function sniffFormat(buf) {
  const b = buf;
  if (b.length >= 4) {
    if (b[0] === 0x66 && b[1] === 0x4c && b[2] === 0x61 && b[3] === 0x43) return 'flac'; // "fLaC"
    if (b[0] === 0x4f && b[1] === 0x67 && b[2] === 0x67 && b[3] === 0x53) return 'ogg'; // "OggS"
    if (b[0] === 0x52 && b[1] === 0x49 && b[2] === 0x46 && b[3] === 0x46) return 'wav'; // "RIFF"
    if (b[0] === 0x49 && b[1] === 0x44 && b[2] === 0x33) return 'mp3'; // "ID3"
  }
  if (b.length >= 8) {
    if (b[4] === 0x66 && b[5] === 0x74 && b[6] === 0x79 && b[7] === 0x70) return 'm4a'; // "ftyp"（MP4/M4A）
  }
  if (b.length >= 2) {
    if (b[0] === 0xff && (b[1] & 0xe0) === 0xe0) return 'mp3'; // MPEG 帧同步
    if (b[0] === 0xff && (b[1] & 0xf6) === 0xf0) return 'aac'; // ADTS
  }
  return 'mp3';
}
